import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:jotit/core/vault_paths.dart';
import 'package:jotit/data/vault/note_file_store.dart';
import 'package:jotit/domain/sync/conflict_writer.dart';
import 'package:path/path.dart' as p;

/// §7.2 — where conflict copies go, and what they must never do.
void main() {
  late Directory vault;
  final when = DateTime.utc(2026, 10, 7, 10, 15, 0);

  setUp(() async {
    vault = await Directory.systemTemp.createTemp('jotit_conf_');
    // A real vault, so the "nothing landed under notes/" assertion inspects a
    // directory that exists rather than passing on a missing-path error.
    await NoteFileStore.ensureLayout(vault.path);
  });

  tearDown(() async {
    if (vault.existsSync()) await vault.delete(recursive: true);
  });

  ConflictSources sources({String? etag = 'W/"opaque-token"'}) =>
      ConflictSources(
        localUid: 'u-local',
        localHash: 'h-local',
        remoteEtag: etag,
        remoteHash: 'h-remote',
        remoteUid: 'u-remote',
      );

  Future<ConflictRecord> writeBoth({
    String path = 'notes/daily/2024-01-01.md',
    List<int>? local,
    List<int>? remote,
    ConflictSources? src,
    DateTime? at,
  }) =>
      ConflictWriter.write(
        vaultRoot: vault.path,
        originalPath: path,
        localBytes: local ?? utf8.encode('# local\n'),
        remoteBytes: remote ?? utf8.encode('# remote\n'),
        sources: src ?? sources(),
        when: at ?? when,
        at: 1,
      );

  String dirOf(String name) => p.join(VaultPaths.conflictsRoot(vault.path), name);

  group('placement', () {
    test('copies land under _conflicts/, never under notes/', () async {
      final rec = await writeBoth();
      expect(Directory(dirOf(rec.directory)).existsSync(), isTrue);

      final inNotes = Directory(VaultPaths.notesRoot(vault.path))
          .listSync(recursive: true)
          .whereType<File>()
          .map((f) => f.path)
          .where((p) => p.contains('local.md') || p.contains('remote.md'));
      expect(inNotes, isEmpty,
          reason: 'ADR-7: copies inside notes/ replicate to every device');
    });

    test('the conflict directory is a sibling of notes/', () async {
      await writeBoth();
      expect(VaultPaths.conflictsRoot(vault.path),
          isNot(startsWith(VaultPaths.notesRoot(vault.path))));
    });

    test('the name carries a timestamp, a sequence and the original stem',
        () async {
      final rec = await writeBoth();
      expect(rec.directory, '20261007-101500-1-2024-01-01');
    });

    test('two conflicts in the same second do not overwrite each other',
        () async {
      final a = await writeBoth();
      final b = await writeBoth();
      final c = await writeBoth();
      expect({a.directory, b.directory, c.directory}.length, 3);
      expect(Directory(dirOf(a.directory)).existsSync(), isTrue);
      expect(Directory(dirOf(c.directory)).existsSync(), isTrue);
    });

    test('an illegal original path still yields a creatable name', () async {
      final rec = await writeBoth(path: 'notes/a:b*c/2024?01.md');
      expect(Directory(dirOf(rec.directory)).existsSync(), isTrue);
      expect(rec.directory.contains('*'), isFalse);
      expect(rec.directory.contains('?'), isFalse);
      expect(rec.directory.contains(':'), isFalse);
    });
  });

  group('bytes are preserved, not annotated', () {
    test('local and remote copies are byte-identical to the input', () async {
      final local = <int>[0xEF, 0xBB, 0xBF, ...utf8.encode('# 本地\r\n')];
      final remote = utf8.encode('# remote\n\nbody\n');
      final rec = await writeBoth(local: local, remote: remote);

      expect(await File(p.join(dirOf(rec.directory), 'local.md')).readAsBytes(),
          local);
      expect(await File(p.join(dirOf(rec.directory), 'remote.md')).readAsBytes(),
          remote);
    });

    test('no banner is added to either copy', () async {
      final local = '# mine\n'.codeUnits;
      final rec = await writeBoth(local: local);
      final written = await File(p.join(dirOf(rec.directory), 'local.md'))
          .readAsString();
      expect(written, '# mine\n');
      expect(written.toLowerCase(), isNot(contains('conflict')));
      expect(written.toLowerCase(), isNot(contains('generated by jotit')));
    });

    test('a non-UTF-8 local copy survives intact', () async {
      // Round-tripping it would replace every undecodable byte with U+FFFD.
      final gbk = <int>[0xD6, 0xD0, 0xCE, 0xC4, 0x0A];
      final rec = await writeBoth(local: gbk);
      expect(
          await File(p.join(dirOf(rec.directory), 'local.md')).readAsBytes(),
          gbk);
    });

    test('CRLF line endings are not normalised', () async {
      final crlf = utf8.encode('a\r\nb\r\n');
      final rec = await writeBoth(local: crlf);
      expect(await File(p.join(dirOf(rec.directory), 'local.md')).readAsBytes(),
          crlf);
    });
  });

  group('one-sided conflicts', () {
    test('delete versus edit keeps the local edit and says remote is absent',
        () async {
      final rec = await ConflictWriter.write(
        vaultRoot: vault.path,
        originalPath: 'notes/a.md',
        localBytes: utf8.encode('# local\n'),
        remoteBytes: null,
        sources: sources(etag: null),
        when: when,
        at: 1,
      );
      expect(rec.hasLocal, isTrue);
      expect(rec.hasRemote, isFalse);
      expect(
          File(p.join(dirOf(rec.directory), 'remote.md')).existsSync(), isFalse,
          reason: 'an empty remote.md would read as "remote said something"');
    });

    test('the reverse keeps the remote edit', () async {
      final rec = await ConflictWriter.write(
        vaultRoot: vault.path,
        originalPath: 'notes/a.md',
        localBytes: null,
        remoteBytes: utf8.encode('# remote\n'),
        sources: sources(),
        when: when,
        at: 1,
      );
      expect(rec.hasLocal, isFalse);
      expect(rec.hasRemote, isTrue);
      expect(File(p.join(dirOf(rec.directory), 'local.md')).existsSync(),
          isFalse);
    });
  });

  group('meta.json', () {
    test('records both sides and the original path', () async {
      final rec = await writeBoth(path: 'notes/x.md');
      final json = jsonDecode(
              await File(p.join(dirOf(rec.directory), 'meta.json')).readAsString())
          as Map<String, Object?>;
      expect(json['original_path'], 'notes/x.md');
      expect(json['local_uid'], 'u-local');
      expect(json['local_content_hash'], 'h-local');
      expect(json['remote_uid'], 'u-remote');
      expect(json['has_local'], isTrue);
      expect(json['has_remote'], isTrue);
    });

    test('stores the ETag verbatim', () async {
      const exotic = 'W/"a b c",  "d"  ';
      final rec = await writeBoth(src: sources(etag: exotic));
      final read = await ConflictWriter.read(vault.path, rec.directory);
      expect(read!.sources.remoteEtag, exotic);
    });

    test('round-trips through read', () async {
      final rec = await writeBoth();
      final read = await ConflictWriter.read(vault.path, rec.directory);
      expect(read!.directory, rec.directory);
      expect(read.originalPath, rec.originalPath);
      expect(read.sources.localHash, 'h-local');
      expect(read.at, 1);
    });

    test('a directory without meta.json is not reported as a conflict',
        () async {
      await Directory(dirOf('hand-made')).create(recursive: true);
      expect(await ConflictWriter.read(vault.path, 'hand-made'), isNull);
      expect(ConflictWriter.pending(vault.path), isEmpty);
    });

    test('a corrupt meta.json does not lose the copies', () async {
      final rec = await writeBoth();
      await File(p.join(dirOf(rec.directory), 'meta.json'))
          .writeAsString('{not json');
      expect(await ConflictWriter.read(vault.path, rec.directory), isNull);
      expect(
          File(p.join(dirOf(rec.directory), 'local.md')).existsSync(), isTrue);
    });
  });

  group('pending list', () {
    test('is empty on a clean vault', () {
      expect(ConflictWriter.pending(vault.path), isEmpty);
    });

    test('lists every unresolved conflict', () async {
      await writeBoth();
      await writeBoth();
      expect(ConflictWriter.pending(vault.path).length, 2);
    });

    test('removal takes it off the list', () async {
      final rec = await writeBoth();
      await ConflictWriter.remove(vault.path, rec.directory);
      expect(ConflictWriter.pending(vault.path), isEmpty);
      expect(Directory(dirOf(rec.directory)).existsSync(), isFalse);
    });

    test('removing something that is not there is harmless', () async {
      await ConflictWriter.remove(vault.path, 'nope');
    });

    test('readSide returns null for a side that was never preserved',
        () async {
      final rec = await ConflictWriter.write(
        vaultRoot: vault.path,
        originalPath: 'notes/a.md',
        localBytes: utf8.encode('# l\n'),
        remoteBytes: null,
        sources: sources(),
        when: when,
        at: 1,
      );
      expect(
          utf8.decode((await ConflictWriter.readSide(
              vault.path, rec.directory, ConflictSide.local))!),
          '# l\n');
      expect(
          await ConflictWriter.readSide(
              vault.path, rec.directory, ConflictSide.remote),
          isNull);
    });
  });

  group('title extraction for the resolution screen', () {
    test('prefers front matter title', () {
      expect(
        ConflictWriter.titleOf(utf8.encode('---\ntitle: 路线图\n---\n# H\n')),
        '路线图',
      );
    });

    test('falls back to the first heading', () {
      expect(ConflictWriter.titleOf(utf8.encode('# 标题\n\nbody\n')), '标题');
    });

    test('returns null for bytes that are not text', () {
      expect(ConflictWriter.titleOf(<int>[0xD6, 0xD0, 0xCE, 0xC4]), isNull);
      expect(ConflictWriter.titleOf(<int>[]), isNull);
    });
  });
}